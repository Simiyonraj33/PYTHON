mark=float(input("Enter the marks: "))
if(mark>=91 and mark<=100):
   print("Grade is O")
elif(mark>=81 and mark<=90):
   print("Grade is A+")
elif(mark>=71 and mark<=80):
   print("Grade is A")
elif(mark>=61 and mark<=70):
   print("Grade is B+")
elif(mark>=51 and mark<=60):
   print("Grade is B")
else:
   print("RA")
